create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  key text primary key check (key in ('service_schedule', 'announcement')),
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create table if not exists public.sms_drafts (
  id bigint generated by default as identity primary key,
  audience text not null check (audience in ('all', 'leaders', 'new', 'custom')),
  message text not null check (char_length(message) between 1 and 320),
  status text not null default 'draft' check (status in ('draft', 'queued', 'sent', 'failed')),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.minstrel_songs (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 1 and 120),
  artist text not null default 'YAM Minstrels' check (char_length(artist) between 1 and 120),
  lyrics text not null check (char_length(lyrics) between 1 and 12000),
  price text not null default '',
  buy_url text not null default '',
  published boolean not null default true,
  display_order integer not null default 0 check (display_order between 0 and 999),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

alter table public.admin_users enable row level security;
alter table public.site_settings enable row level security;
alter table public.sms_drafts enable row level security;
alter table public.minstrel_songs enable row level security;

create or replace function public.is_yam_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_yam_admin() from public;
grant execute on function public.is_yam_admin() to authenticated;

create policy "Admins can verify their membership"
on public.admin_users for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "Public site settings are readable"
on public.site_settings for select
to anon, authenticated
using (true);

create policy "Admins can insert site settings"
on public.site_settings for insert
to authenticated
with check ((select public.is_yam_admin()));

create policy "Admins can update site settings"
on public.site_settings for update
to authenticated
using ((select public.is_yam_admin()))
with check ((select public.is_yam_admin()));

create policy "Admins can delete site settings"
on public.site_settings for delete
to authenticated
using ((select public.is_yam_admin()));

create policy "Admins can manage SMS drafts"
on public.sms_drafts for all
to authenticated
using ((select public.is_yam_admin()))
with check ((select public.is_yam_admin()));

create policy "Published minstrel songs are publicly readable"
on public.minstrel_songs for select
to anon, authenticated
using (published);

create policy "Admins can read minstrel drafts"
on public.minstrel_songs for select
to authenticated
using ((select public.is_yam_admin()));

create policy "Admins can insert minstrel songs"
on public.minstrel_songs for insert
to authenticated
with check ((select public.is_yam_admin()));

create policy "Admins can update minstrel songs"
on public.minstrel_songs for update
to authenticated
using ((select public.is_yam_admin()))
with check ((select public.is_yam_admin()));

create policy "Admins can delete minstrel songs"
on public.minstrel_songs for delete
to authenticated
using ((select public.is_yam_admin()));

revoke all on public.admin_users from anon, authenticated;
